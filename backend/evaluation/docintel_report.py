"""Markdown rendering of the Phase 3 evaluation report (docs/extraction-evaluation-results.md)."""
from __future__ import annotations


def _f(x, digits=3):
    return "–" if x is None else (f"{x:.{digits}f}" if isinstance(x, float) else str(x))


def _prf_row(name: str, s: dict) -> str:
    return (f"| {name} | {s['slots']} | {_f(s['exact_match'])} | {_f(s['precision'])} | {_f(s['recall'])} | "
            f"{_f(s['f1'])} |")


def render(r: dict) -> str:
    m = r["meta"]
    L = ["# NEXUS AI document-intelligence evaluation", "",
         f"> Generated by `python scripts/evaluate_docintel.py` at {m['generated_at']}; do not edit by hand.",
         f"> Corpus manifest sha256 `{m['corpus_sha256']}…`; {m['platform']}; OCR: "
         f"{(m['ocr'] or {}).get('engine', 'n/a')} {(m['ocr'] or {}).get('version', '')} "
         f"({(m['ocr'] or {}).get('languages', '')}); provider: {m['provider']}.", "",
         "## Corpus", "",
         f"- {m['documents']} fictional documents ({m['splits']['dev']} dev / {m['splits']['test']} test): "
         f"{m['types']['contract']} contracts, {m['types']['invoice']} invoices, {m['types']['unknown']} other.",
         f"- Formats: {', '.join(f'{k} {v}' for k, v in sorted(m['formats'].items()))}; "
         f"{m['scanned_pages']} scanned pages; languages: {m['languages']}; tenants: {', '.join(m['tenants'])}.",
         f"- Uploaded and processed through the API: {m['uploads_ok']}/{m['documents']}. Total run time {m['total_seconds']} s.",
         "- Ground truth = the authored values each document was generated from (never extractor output). "
         "Test-split documents include label wordings the rules were not written for.", "",
         "## Field extraction (offline rules provider)", "",
         "| Group | slots | exact match | precision | recall | F1 |", "|---|---|---|---|---|---|"]
    g = r["extraction"]["groups"]
    for key in ["all", "split:dev", "split:test", "type:contract", "type:invoice", "language:en", "language:hr"] + \
               sorted(k for k in g if k.startswith("format:")):
        if key in g:
            L.append(_prf_row(key, g[key]))
    mf = r["extraction"]["missing_fields"]
    L += ["", f"Missing-field detection: {mf['correctly_left_empty']}/{mf['ground_truth_missing']} absent fields "
              f"left empty ({_f(mf['detection_rate'])}); {mf['hallucinated']} values invented for absent fields. "
              f"Fields extracted from 'unknown' documents: {r['extraction']['fields_extracted_from_unknown_documents']}.",
          "", "### Per field", "", "| Field | slots | exact | precision | recall | F1 |", "|---|---|---|---|---|---|"]
    for k, s in r["extraction"]["per_field"].items():
        L.append(_prf_row(k, s))
    c = r["classification"]
    L += ["", "## Classification", "", f"Accuracy {_f(c['accuracy'])}. Confusion (ground truth → predicted): "
          + "; ".join(f"{gt}: {pred}" for gt, pred in c["confusion"].items()), ""]
    e = r["evidence"]
    L += ["## Evidence", "", "| Metric | Value |", "|---|---|",
          f"| fields with a value | {e['fields_with_value']} |",
          f"| evidence reference valid (right document, existing page, text on that page) | {_f(e['evidence_reference_valid_rate'])} |",
          f"| evidence supports the value (exact / normalized match) | {_f(e['evidence_support_rate'])} |",
          f"| unsupported-field rate | {_f(e['unsupported_field_rate'])} |",
          f"| correct page attribution ({e['page_attribution_checked']} checked) | {_f(e['page_attribution_accuracy'])} |",
          "", f"Method: {e['method']}.", ""]
    t, v = r["tables"], r["validation"]
    L += ["## Tables and validation", "", "| Metric | Value |", "|---|---|",
          f"| line-item cell (row/column) association accuracy ({t['cells']} cells) | {_f(t['cell_association_accuracy'])} |",
          f"| line-item exact match ({t['rows']} rows) | {_f(t['line_item_exact_match'])} |",
          f"| extra predicted rows | {t['extra_predicted_rows']} |",
          f"| numeric reconciliation accuracy (invoices) | {_f(v['numeric_reconciliation_accuracy'])} |",
          f"| invalid-field detection precision / recall | {_f(v['invalid_field_detection']['precision'])} / "
          f"{_f(v['invalid_field_detection']['recall'])} |", ""]
    o = r["ocr"]
    L += ["## OCR (scanned pages)", "", f"{o['processed']}/{o['scanned_pages']} pages processed; mean CER "
          f"{_f(o['mean_cer'], 4)}, mean WER {_f(o['mean_wer'], 4)}, mean key-token recall {_f(o['mean_key_token_recall'])}; "
          f"mean upload+processing time per scanned document {o['upload_ms_per_scanned_document_mean']} ms.", "",
          "| Document | page | CER | WER | key tokens | Tesseract mean conf. | deskew ° |", "|---|---|---|---|---|---|---|"]
    for p in o["pages"]:
        L.append(f"| {p['document']} | {p['page']} | {_f(p.get('cer'), 4)} | {_f(p.get('wer'), 4)} | "
                 f"{_f(p.get('key_token_recall'))} | {_f(p.get('mean_confidence'))} | {_f(p.get('deskew_degrees'))} |")
    L += ["", o["note"] + ".", ""]
    rv = r["review"]
    L += ["## Human review (simulated through the review API)", "", "| Metric | Value |", "|---|---|",
          f"| correction rate ({rv['corrected_fields']}/{rv['field_slots']} field slots) | {_f(rv['correction_rate'])} |",
          f"| approved / rejected | {rv['approved']} / {rv['rejected']} |",
          f"| approval consistency (approved values == ground truth) | {_f(rv['approval_consistency'])} |",
          f"| invalid documents whose approval was blocked by validation | {rv['invalid_approvals_blocked']}/{rv['invalid_documents']} |",
          f"| validation false-accept rate | {_f(rv['validation_false_accept_rate'])} |",
          f"| extractions with errors that were NOT flagged (status pending) | {_f(rv['extraction_errors_not_flagged_rate'])} "
          f"of {rv['extractions_with_errors']} |",
          f"| approvals needing an override | {rv['approvals_needing_override']} |",
          f"| stale concurrent edit refused (HTTP 409) | {rv['optimistic_lock_conflict_detected']} |",
          "", f"Policy: {rv['policy']}.", ""]
    L += ["## Multi-document questions", "", "| Query | before review P / R | after review P / R | exact after review |",
          "|---|---|---|---|"]
    for qid, after in r["queries_after_review"]["queries"].items():
        b = r["queries_before_review"]["queries"][qid]
        L.append(f"| {qid} | {_f(b['precision'])} / {_f(b['recall'])} | {_f(after['precision'])} / "
                 f"{_f(after['recall'])} | {after['exact']} |")
    L += ["", "Expected answers come from the ground truth and an independent ACL oracle; rejected extractions are "
              "excluded after review.", ""]
    s = r["security"]
    L += ["## Security", "", "| Check | Result |", "|---|---|", f"| requests checked | {s['checks']} |"]
    for k in ("unauthorized_extraction_access", "cross_tenant_leakage", "unauthorized_review_actions",
              "unauthorized_comparisons", "total_violations", "false_denials"):
        L.append(f"| {k.replace('_', ' ')} | {s[k]} |")
    L += ["", "## LLM extraction provider", "", f"**{r['llm_provider']['status']}**: {r['llm_provider']['reason']}.", "",
          "## Per-document failure analysis", ""]
    for d in r["failures"]:
        if d.get("problems"):
            L.append(f"- **{d['document']}** ({d['split']}, {d['format']}, {d['language']}; {d['notes'] or 'no note'}):")
            L += [f"  - {p}" for p in d["problems"]]
        elif d.get("error"):
            L.append(f"- **{d['document']}**: {d['error']}")
    clean = [d["document"] for d in r["failures"] if not d.get("problems") and not d.get("error")]
    L += ["", f"Documents without any field error: {len(clean)} ({', '.join(clean)}).", ""]
    return "\n".join(L)
