"""Render the evaluation JSON report as Markdown (docs/benchmark-results.md, README section)."""
from __future__ import annotations

MODE_LABEL = {"bm25": "BM25 (Python baseline)", "lexical": "PostgreSQL FTS",
              "semantic": "Semantic (pgvector)", "hybrid": "Hybrid RRF"}


def _f(v, digits=3):
    return "–" if v is None else (f"{v:.{digits}f}" if isinstance(v, float) else str(v))


def comparison_table(report: dict, split: str = "test") -> str:
    lines = ["| Mode | Recall@1 | Recall@5 | Recall@10 | Precision@5 | MRR@10 | nDCG@5 | Hit@5 | p50 ms | p95 ms |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for mode, m in report["benchmark"]["modes"].items():
        a, lat = m[split], m["latency"]["wall_ms"]
        lines.append(f"| {MODE_LABEL[mode]} | {_f(a['recall@1'])} | {_f(a['recall@5'])} | "
                     f"{_f(a['recall@10'])} | {_f(a['precision@5'])} | {_f(a['mrr@10'])} | "
                     f"{_f(a['ndcg@5'])} | {_f(a['hit_rate@5'])} | {_f(lat['p50'], 1)} | {_f(lat['p95'], 1)} |")
    return "\n".join(lines)


def _breakdown(report: dict, key: str, metric: str = "ndcg@5") -> str:
    modes = list(report["benchmark"]["modes"])
    groups = sorted({g for m in modes for g in report["benchmark"]["modes"][m][key]})
    lines = ["| " + key.removeprefix("by_") + " | n | " + " | ".join(MODE_LABEL[m] for m in modes) + " |",
             "|---|---|" + "---|" * len(modes)]
    for g in groups:
        first = report["benchmark"]["modes"][modes[0]][key].get(g, {})
        vals = [_f(report["benchmark"]["modes"][m][key].get(g, {}).get(metric)) for m in modes]
        lines.append(f"| {g} | {first.get('n', 0)} | " + " | ".join(vals) + " |")
    return "\n".join(lines)


ABST_HEADER = ["| Policy | split | answered/answerable (TP) | abstained/answerable (FN) | "
               "answered/unanswerable (FP) | abstained/unanswerable (TN) | answerability precision | "
               "answerable recall | false abstention | false answerability | balanced acc. | "
               "harmful FN (evidence was in top-5) |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|"]


def _abstention_row(name, split, m):
    c = m["confusion"]
    return (f"| {name} | {split} | {c['answered_answerable']} | {c['abstained_answerable']} | "
            f"{c['answered_unanswerable']} | {c['abstained_unanswerable']} | "
            f"{_f(m['answerability_precision'])} | {_f(m['answerable_recall'])} | "
            f"{_f(m['false_abstention_rate'])} | {_f(m['false_answerability_rate'])} | "
            f"{_f(m['balanced_accuracy'])} | {m.get('harmful_false_abstentions', '–')} |")


def _policy_label(pol: dict) -> str:
    parts = ["identifier rule" if pol.get("require_identifier_match") else "no identifier rule"]
    if pol.get("min_semantic_similarity") is not None:
        parts.append(f"chunk cos ≥ {pol['min_semantic_similarity']}")
    if pol.get("min_sentence_similarity") is not None:
        parts.append(f"sentence cos ≥ {pol['min_sentence_similarity']}")
    if pol.get("min_term_coverage") is not None:
        parts.append(f"term coverage ≥ {pol['min_term_coverage']}")
    if pol.get("accept_on_branch_agreement"):
        parts.append("branch agreement")
    return ", ".join(parts) if pol.get("enabled", True) else "disabled"


def _significance(report: dict) -> str:
    sig = report["benchmark"].get("significance_test_split")
    if not sig or not sig.get("n_cases"):
        return ""
    lines = [f"Bootstrap 95 % CI on the test split (n = {sig['n_cases']}, 2,000 resamples, seed 0):", "",
             "| Mode | nDCG@5 CI | Recall@5 CI | hybrid − mode, nDCG@5 (CI) | hybrid − mode, Recall@5 (CI) |",
             "|---|---|---|---|---|"]
    for mode in report["benchmark"]["modes"]:
        n_ci, r_ci = sig["ci95"]["ndcg@5"][mode], sig["ci95"]["recall@5"][mode]
        if mode == "hybrid":
            dn = dr = "–"
        else:
            a, b = sig["hybrid_minus"]["ndcg@5"][mode], sig["hybrid_minus"]["recall@5"][mode]
            dn = f"{a['mean_diff']:+.3f} [{a['ci95'][0]:+.3f}, {a['ci95'][1]:+.3f}]"
            dr = f"{b['mean_diff']:+.3f} [{b['ci95'][0]:+.3f}, {b['ci95'][1]:+.3f}]"
        lines.append(f"| {MODE_LABEL[mode]} | [{n_ci[0]:.3f}, {n_ci[1]:.3f}] | [{r_ci[0]:.3f}, {r_ci[1]:.3f}] | {dn} | {dr} |")
    lines += ["", "A difference is only meaningful if its CI excludes 0."]
    return "\n".join(lines)


def render(report: dict) -> str:
    md = report["meta"]
    out = [
        "# NEXUS AI benchmark results",
        "",
        f"> Generated by `python scripts/evaluate.py` at {md['generated_at']} — do not edit by hand.",
        f"> Dataset `eval/retrieval.jsonl` sha256 `{md['dataset_sha256'][:16]}…`, "
        f"model `{md['index']['model']}` @ `{md['index']['model_revision'][:12]}`, "
        f"{md['platform']}, Python {md['python']}.",
        "",
        "## Setup",
        "",
        f"- Corpus: {md['corpus']['documents']} synthetic documents, {md['corpus']['chunks']} chunks "
        f"(production chunker), tenants {', '.join(md['corpus']['tenants'])}, languages {md['corpus']['languages']}.",
        f"- Cases: {md['cases']['total']} ({md['cases']['dev']} dev / {md['cases']['test']} test), "
        f"{md['cases']['answerable']} answerable, {md['cases']['unanswerable']} unanswerable or unauthorized.",
        f"- Index verified in PostgreSQL: {md['index']['chunks']} chunks, {md['index']['embeddings']} "
        f"persisted embeddings (vector_dims = {md['index']['vector_dims']}), {md['index']['tsvector_rows']} tsvector rows.",
        "- Relevance metrics are macro-averaged over **answerable** cases only; unanswerable and "
        "authorization cases are scored by abstention and security checks instead.",
        "",
        "## Retrieval comparison — held-out test split (top_k = 10)",
        "",
        comparison_table(report, "test"),
        "",
        "Latency columns are end-to-end retrieval wall time per query over all cases in a warm process "
        "on the machine above (not a load test).",
        "",
        _significance(report),
        "",
        "### All answerable cases (dev + test)",
        "",
        comparison_table(report, "all"),
        "",
        "### nDCG@5 by category (all cases)",
        "",
        _breakdown(report, "by_category"),
        "",
        "### nDCG@5 by question language",
        "",
        _breakdown(report, "by_language"),
        "",
        "### nDCG@5 by persona",
        "",
        _breakdown(report, "by_persona"),
        "",
        "### Latency components (ms, warm)",
        "",
        "| Mode | wall p50 | wall p95 | embedding p50 | semantic DB p50 | lexical p50 | fusion p50 | cold first query |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for mode, m in report["benchmark"]["modes"].items():
        lat = m["latency"]
        def c(name):
            return _f(lat.get(f"{name}_ms", {}).get("p50"), 1)
        out.append(f"| {MODE_LABEL[mode]} | {_f(lat['wall_ms']['p50'], 1)} | {_f(lat['wall_ms']['p95'], 1)} | "
                   f"{c('embedding')} | {c('semantic_db')} | {c('lexical')} | {c('fusion')} | "
                   f"{_f(report['benchmark']['cold'][mode], 1)} |")
    out += ["", f"Cold start (model load + first query embedding in a fresh process): "
                f"{md['cold_start_model_load_and_first_query_ms']:.0f} ms.", ""]

    ab = report.get("ablation")
    if ab:
        d, s = ab["default"], ab["selected"]
        out += [
            "## Hybrid RRF ablation",
            "",
            f"{ab['grid_size']} configurations (weights × candidates × k). Selection: {ab['selection_metric']}. "
            "The test split was not used for selection.",
            "",
            "| Config | candidates | k | w_lexical | w_semantic | dev nDCG@5 | test nDCG@5 | test Recall@5 | test MRR@10 |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for name, row in (("default", d), ("selected on dev", s)):
            cfg = row["config"]
            out.append(f"| {name} | {cfg['candidates']} | {cfg['rrf_k']} | {cfg['weights']['lexical']} | "
                       f"{cfg['weights']['semantic']} | {_f(row['dev']['ndcg@5'])} | {_f(row['test']['ndcg@5'])} | "
                       f"{_f(row['test']['recall@5'])} | {_f(row['test']['mrr@10'])} |")
        out += ["", f"Test delta (selected − default): nDCG@5 {ab['test_delta_ndcg@5']:+.4f}, "
                    f"Recall@5 {ab['test_delta_recall@5']:+.4f}.", "",
                "Top dev configurations:", "",
                "| candidates | k | w_lexical | w_semantic | dev nDCG@5 | dev MRR@10 | dev Recall@5 |",
                "|---|---|---|---|---|---|---|"]
        for row in sorted(ab["rows"], key=lambda r: -r["dev"]["ndcg@5"])[:8]:
            cfg = row["config"]
            out.append(f"| {cfg['candidates']} | {cfg['rrf_k']} | {cfg['weights']['lexical']} | "
                       f"{cfg['weights']['semantic']} | {_f(row['dev']['ndcg@5'])} | {_f(row['dev']['mrr@10'])} | "
                       f"{_f(row['dev']['recall@5'])} |")
        out.append("")

    ext = report.get("extraction")
    if ext:
        out += ["## Offline answer extraction (dev → test)", "",
                f"Retrieval fixed to `{ext['retrieval']}`, cases with expected facts only. "
                f"{ext['grid_size']} configurations; selection: {ext['selection_metric']}.", "",
                "| Extractor | split | n | answer fact recall | … given fact retrieved | mean answer chars | "
                "non-verbatim quotes |", "|---|---|---|---|---|---|---|"]
        rows = [("Phase 2c: first 330 chars of top-3 chunks", ext["legacy_first_330"]),
                (f"query-aware, selected on dev `{ext['selected']['config']}`", ext["selected"])]
        for name, block in rows:
            for split in ("dev", "test"):
                m = block[split]
                out.append(f"| {name} | {split} | {m['n']} | {_f(m['answer_fact_recall'])} | "
                           f"{_f(m['answer_fact_recall_given_retrieved'])} | {_f(m['mean_answer_chars'], 0)} | "
                           f"{m['verbatim_violations']} |")
        out.append("")

    cal = report.get("calibration")
    if cal:
        out += ["## Evidence sufficiency (abstention)", "",
                f"{cal['candidates_evaluated']} candidate policies per mode, selected on **dev** signals only "
                f"({cal['objective']}). Similarities are heuristic signals, **not** probabilities. "
                "Positive class = the system answers.", ""]
        for mode, m in cal["modes"].items():
            sel = m["selected"]
            out += [f"### {MODE_LABEL[mode]}", "",
                    f"Selected: `{sel['family']}` — {_policy_label(sel['policy'])}.", ""] + ABST_HEADER
            out.append(_abstention_row("no policy", "test", m["baselines"]["no_policy"]["test"]))
            prev = m.get("previous_policy")
            if prev:
                out.append(_abstention_row(f"Phase 2c ({_policy_label(prev['policy'])})", "dev", prev["dev"]))
                out.append(_abstention_row(f"Phase 2c ({_policy_label(prev['policy'])})", "test", prev["test"]))
            for fam, f in m["families"].items():
                tag = " **(selected)**" if fam == sel["family"] else ""
                out.append(_abstention_row(f"{fam}: {_policy_label(f['policy'])}{tag}", "dev", f["dev"]))
                out.append(_abstention_row(f"{fam}: {_policy_label(f['policy'])}{tag}", "test", f["test"]))
            out += ["", "Selected policy on test, by question language and for cross-language questions:", ""] + ABST_HEADER
            for lang, mm in m["selected_test_by_language"].items():
                out.append(_abstention_row(f"question language = {lang}", "test", mm))
            out.append(_abstention_row("category = cross_language", "test", m["selected_test_cross_language"]))
            if prev:
                out.append(_abstention_row("category = cross_language (Phase 2c policy)", "test",
                                           prev["test_cross_language"]))
            out += ["", "Dev signal distributions (min / p50 / max):", ""]
            for k, v in m["similarity_distribution_dev"].items():
                out.append(f"- `{k}`: {v}")
            out.append("")

    e2e = report.get("end_to_end")
    if e2e:
        out += ["## End-to-end API: citations, answers, abstention", "",
                f"Evidence policy used: `{e2e['policy']}`.", "",
                "| Mode | citations valid | source mapping errors | non-verbatim quotes | retrieval fact recall@5 | "
                "answer fact recall | unsupported fact answers | unanswerable abstained | answerable abstained |",
                "|---|---|---|---|---|---|---|---|---|"]
        for mode, m in e2e["per_mode"].items():
            c, q, a = m["citations"], m["answer_quality"], m["abstention"]
            out.append(f"| {MODE_LABEL[mode]} | {c['valid']}/{c['total']} | {c['source_mapping_errors']} | "
                       f"{c.get('quotes_not_verbatim_in_cited_chunk', '–')}/{c.get('extractive_quotes', '–')} | "
                       f"{_f(q['retrieval_fact_recall@5'])} | {_f(q['answer_fact_recall'])} | "
                       f"{q['unsupported_fact_answers']} | {a['unanswerable_abstained']}/{a['unanswerable_total']} | "
                       f"{a['answerable_abstained']}/{a['answerable_total']} |")
        gen = next(iter(e2e["per_mode"].values()))["answer_quality"]["generator"]
        out += ["", f"Answer generator: {gen}. Answer fact recall measures whether the expected facts "
                    "appear in the generated text; no LLM judge is used.", ""]

    sec = report.get("security")
    if sec:
        out += ["## Security", "", "| Check | Result |", "|---|---|"]
        for k, v in sec.items():
            out.append(f"| {k} | {v} |")
        out.append("")
    return "\n".join(out) + "\n"


def readme_section(report: dict) -> str:
    md = report["meta"]
    lines = [
        f"Measured by `scripts/evaluate.py` on {md['generated_at'][:10]} — {md['cases']['total']} labeled "
        f"questions over {md['corpus']['documents']} synthetic documents ({md['corpus']['chunks']} chunks); "
        f"held-out **test split** ({md['cases']['test']} questions), answerable cases only.",
        "",
        comparison_table(report, "test"),
        "",
    ]
    cal = report.get("calibration", {}).get("modes", {}).get("hybrid")
    if cal:
        t = cal["selected"]["test"]
        prev = cal.get("previous_policy", {}).get("test")
        lines.append(
            f"Hybrid evidence policy ({_policy_label(cal['selected']['policy'])}; chosen on dev) on test: "
            f"answerable recall {t['answerable_recall']:.3f}, unanswerable detection "
            f"{t['unanswerable_detection']:.3f}, answerability precision {_f(t['answerability_precision'])}"
            + (f" (Phase 2c policy: {prev['answerable_recall']:.3f} / {prev['unanswerable_detection']:.3f})."
               if prev else "."))
    ext = report.get("extraction")
    if ext:
        lines.append(
            f"Offline answer fact recall on test (hybrid top-5): {ext['legacy_first_330']['test']['answer_fact_recall']:.3f} "
            f"(Phase 2c, first 330 chars) → {ext['selected']['test']['answer_fact_recall']:.3f} (query-aware quotes).")
    sec = report.get("security", {})
    if sec:
        lines.append(f"Authorization violations: {sec.get('total_violations')} "
                     f"(retrieval candidates, API sources, citations, LLM prompts, forbidden text in output).")
    lines.append("Full results: [docs/benchmark-results.md](docs/benchmark-results.md).")
    return "\n".join(lines)
