"""Object storage for original documents (Phase 4D).

Backends
    s3      any S3-compatible API: MinIO locally / in CI, AWS S3 (virtual-hosted or path style),
            private bucket, SHA-256 checksums verified by the server on upload
            (x-amz-checksum-sha256), optional SSE (AES256 / aws:kms), bounded retries + timeouts
    local   a directory (v0.1-v0.3 compatibility, SQLite demos and unit tests)

Object keys are generated by the server only: tenants/<tenant>/documents/<uuid>/v<n>/original.
Nothing from the user's filename or request reaches a key; every key is validated against a
strict pattern before any storage call, and the local backend additionally refuses any path
that would resolve outside its root. Legacy v0.3 local keys (<uuid>.<ext>) remain readable.

The bucket is never public: downloads are streamed by the API after authorization, or, when
PRESIGNED_DOWNLOADS=true, redirected to a short-lived presigned GET URL issued only after the
same authorization check.
"""
from __future__ import annotations

import base64
import hashlib
import logging
import os
import re
import tempfile
import threading
import time
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from .config import Settings
from .observability.metrics import STORAGE_DURATION, STORAGE_OPS
from .observability.tracing import span

log = logging.getLogger("nexus.storage")
KEY = re.compile(r"^tenants/[a-z0-9][a-z0-9_-]{0,39}/documents/[0-9a-f-]{36}/v[0-9]{1,6}/original$")
# v0.1-v0.3 local keys ("<document id>.<ext>"): one path segment, no dots before the extension.
LEGACY_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,80}\.(pdf|docx|xlsx|txt|md)$")
UUID = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
TENANT = re.compile(r"^[a-z0-9][a-z0-9_-]{0,39}$")
CHUNK = 256 * 1024


class StorageError(RuntimeError):
    code = "storage_error"


class StorageUnavailable(StorageError):
    code = "storage_unavailable"


class ObjectMissing(StorageError):
    code = "object_missing"


class InvalidObjectKey(StorageError):
    code = "invalid_key"


class IntegrityError(StorageError):
    code = "checksum_mismatch"


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    sha256: str | None
    content_type: str | None
    last_modified: datetime | None = None


def object_key(tenant_id: str, document_id: str, version: int) -> str:
    if not TENANT.match(tenant_id or "") or not UUID.match(document_id or "") or not 1 <= version <= 999_999:
        raise InvalidObjectKey("refusing to build an object key from unexpected identifiers")
    return f"tenants/{tenant_id}/documents/{document_id}/v{version}/original"


def check_key(key: str, allow_legacy: bool = False) -> str:
    if isinstance(key, str) and (KEY.match(key) or (allow_legacy and LEGACY_KEY.match(key))):
        return key
    raise InvalidObjectKey("invalid object key")


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class _Timed:
    def __init__(self, operation: str):
        self.operation = operation

    def __enter__(self):
        self.start = time.perf_counter()
        return self

    def __exit__(self, exc_type, exc, tb):
        STORAGE_DURATION.labels(self.operation).observe(time.perf_counter() - self.start)
        outcome = "ok" if exc_type is None else ("missing" if issubclass(exc_type, ObjectMissing) else "error")
        STORAGE_OPS.labels(self.operation, outcome).inc()
        return False


class LocalObjectStore:
    backend = "local"

    def __init__(self, root: Path):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        check_key(key, allow_legacy=True)
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise InvalidObjectKey("object key resolves outside the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str, sha256: str, metadata: dict | None = None) -> StoredObject:
        with _Timed("put"), span("storage.put", **{"storage.backend": "local"}):
            if sha256_hex(data) != sha256:
                raise IntegrityError("content does not match the expected SHA-256")
            path = self._path(key)
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            try:
                with os.fdopen(fd, "wb") as handle:
                    handle.write(data)
                os.replace(tmp, path)  # atomic: readers never see a partial object
            except OSError as exc:
                Path(tmp).unlink(missing_ok=True)
                raise StorageUnavailable(f"local storage write failed: {type(exc).__name__}") from None
            return StoredObject(key, len(data), sha256, content_type)

    def get(self, key: str) -> bytes:
        with _Timed("get"), span("storage.get", **{"storage.backend": "local"}):
            path = self._path(key)
            if not path.is_file():
                raise ObjectMissing("object not found")
            return path.read_bytes()

    def stream(self, key: str) -> Iterator[bytes]:
        path = self._path(key)
        if not path.is_file():
            raise ObjectMissing("object not found")
        STORAGE_OPS.labels("stream", "ok").inc()

        def chunks():
            with path.open("rb") as handle:
                while block := handle.read(CHUNK):
                    yield block
        return chunks()

    def head(self, key: str) -> StoredObject | None:
        path = self._path(key)
        if not path.is_file():
            return None
        stat = path.stat()
        return StoredObject(key, stat.st_size, None, None,
                            datetime.fromtimestamp(stat.st_mtime, timezone.utc))

    def delete(self, key: str) -> bool:
        with _Timed("delete"):
            path = self._path(key)
            existed = path.is_file()
            path.unlink(missing_ok=True)
            return existed

    def list_keys(self, prefix: str = "tenants/") -> Iterator[StoredObject]:
        base = self.root / prefix
        if not base.exists():
            return iter(())
        return (StoredObject(p.relative_to(self.root).as_posix(), p.stat().st_size, None, None,
                             datetime.fromtimestamp(p.stat().st_mtime, timezone.utc))
                for p in base.rglob("original") if p.is_file())

    def presigned_get(self, key: str, filename: str, content_type: str | None, ttl: int) -> str:
        raise StorageError("presigned URLs need the s3 backend")

    def healthy(self) -> bool:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            return os.access(self.root, os.W_OK)
        except OSError:
            return False


class S3ObjectStore:
    backend = "s3"

    def __init__(self, cfg: Settings):
        import boto3
        from botocore.config import Config

        self.bucket = cfg.s3_bucket
        self.sse = cfg.s3_server_side_encryption or None
        client_cfg = Config(
            signature_version="s3v4", connect_timeout=cfg.s3_connect_timeout,
            read_timeout=cfg.s3_read_timeout,
            retries={"max_attempts": max(1, cfg.s3_max_attempts), "mode": "standard"},
            s3={"addressing_style": "path" if cfg.s3_force_path_style else "auto"},
            request_checksum_calculation="when_required", response_checksum_validation="when_required",
        )
        credentials = {}
        if cfg.s3_access_key_id and cfg.s3_secret_access_key:
            credentials = {"aws_access_key_id": cfg.s3_access_key_id,
                           "aws_secret_access_key": cfg.s3_secret_access_key}
        session = boto3.session.Session()
        self.client = session.client("s3", endpoint_url=cfg.s3_endpoint_url or None,
                                     region_name=cfg.s3_region, config=client_cfg, **credentials)
        self.presign_client = session.client(
            "s3", endpoint_url=cfg.s3_public_endpoint_url or cfg.s3_endpoint_url or None,
            region_name=cfg.s3_region, config=client_cfg, **credentials)

    @staticmethod
    def _translate(exc: Exception) -> StorageError:
        from botocore.exceptions import BotoCoreError, ClientError

        if isinstance(exc, ClientError):
            code = str(exc.response.get("Error", {}).get("Code", ""))
            status = exc.response.get("ResponseMetadata", {}).get("HTTPStatusCode")
            if code in ("NoSuchKey", "404", "NotFound") or status == 404:
                return ObjectMissing("object not found")
            if code in ("BadDigest", "InvalidDigest", "XAmzContentChecksumMismatch", "InvalidChecksum"):
                return IntegrityError("storage rejected the upload checksum")
            if code in ("AccessDenied", "InvalidAccessKeyId", "SignatureDoesNotMatch", "NoSuchBucket"):
                return StorageUnavailable(f"object storage refused the request ({code})")
            return StorageUnavailable(f"object storage error ({code or status})")
        if isinstance(exc, BotoCoreError):
            return StorageUnavailable(f"object storage unreachable ({type(exc).__name__})")
        return StorageUnavailable(f"object storage failure ({type(exc).__name__})")

    def put(self, key: str, data: bytes, content_type: str, sha256: str, metadata: dict | None = None) -> StoredObject:
        check_key(key)
        if sha256_hex(data) != sha256:
            raise IntegrityError("content does not match the expected SHA-256")
        args = {"Bucket": self.bucket, "Key": key, "Body": data, "ContentType": content_type,
                "ChecksumAlgorithm": "SHA256",
                "ChecksumSHA256": base64.b64encode(bytes.fromhex(sha256)).decode("ascii"),
                "Metadata": {k: str(v)[:200] for k, v in (metadata or {}).items()} | {"sha256": sha256}}
        if self.sse:
            args["ServerSideEncryption"] = self.sse
        with _Timed("put"), span("storage.put", **{"storage.backend": "s3", "storage.bytes": len(data)}):
            try:
                self.client.put_object(**args)
            except Exception as exc:  # noqa: BLE001 - translated to a storage category
                raise self._translate(exc) from None
        return StoredObject(key, len(data), sha256, content_type)

    def get(self, key: str) -> bytes:
        check_key(key)
        with _Timed("get"), span("storage.get", **{"storage.backend": "s3"}):
            try:
                body = self.client.get_object(Bucket=self.bucket, Key=key)["Body"]
                return body.read()
            except Exception as exc:  # noqa: BLE001
                raise self._translate(exc) from None

    def stream(self, key: str) -> Iterator[bytes]:
        check_key(key)
        with _Timed("stream"):
            try:
                body = self.client.get_object(Bucket=self.bucket, Key=key)["Body"]
            except Exception as exc:  # noqa: BLE001
                raise self._translate(exc) from None
        return body.iter_chunks(CHUNK)

    def head(self, key: str) -> StoredObject | None:
        check_key(key)
        try:
            meta = self.client.head_object(Bucket=self.bucket, Key=key)
        except Exception as exc:  # noqa: BLE001
            translated = self._translate(exc)
            if isinstance(translated, ObjectMissing):
                return None
            raise translated from None
        return StoredObject(key, int(meta.get("ContentLength", 0)), (meta.get("Metadata") or {}).get("sha256"),
                            meta.get("ContentType"), meta.get("LastModified"))

    def delete(self, key: str) -> bool:
        check_key(key)
        with _Timed("delete"), span("storage.delete", **{"storage.backend": "s3"}):
            try:
                self.client.delete_object(Bucket=self.bucket, Key=key)  # idempotent in S3
            except Exception as exc:  # noqa: BLE001
                translated = self._translate(exc)
                if isinstance(translated, ObjectMissing):
                    return False
                raise translated from None
        return True

    def list_keys(self, prefix: str = "tenants/") -> Iterator[StoredObject]:
        paginator = self.client.get_paginator("list_objects_v2")
        try:
            for page in paginator.paginate(Bucket=self.bucket, Prefix=prefix):
                for item in page.get("Contents", []):
                    yield StoredObject(item["Key"], int(item.get("Size", 0)), None, None, item.get("LastModified"))
        except Exception as exc:  # noqa: BLE001
            raise self._translate(exc) from None

    def presigned_get(self, key: str, filename: str, content_type: str | None, ttl: int) -> str:
        check_key(key)
        safe_name = re.sub(r"[^A-Za-z0-9._ -]", "_", filename)[:150] or "document"
        params = {"Bucket": self.bucket, "Key": key,
                  "ResponseContentDisposition": f'attachment; filename="{safe_name}"'}
        if content_type:
            params["ResponseContentType"] = content_type
        STORAGE_OPS.labels("presign", "ok").inc()
        return self.presign_client.generate_presigned_url("get_object", Params=params,
                                                          ExpiresIn=max(5, min(ttl, 900)))

    def healthy(self) -> bool:
        try:
            self.client.head_bucket(Bucket=self.bucket)
            return True
        except Exception:  # noqa: BLE001
            return False

    def ensure_bucket(self) -> None:
        """Create the private bucket if missing (local MinIO / CI); block public access on AWS."""
        from botocore.exceptions import ClientError

        try:
            self.client.head_bucket(Bucket=self.bucket)
        except ClientError:
            self.client.create_bucket(Bucket=self.bucket)
        try:
            self.client.put_public_access_block(Bucket=self.bucket, PublicAccessBlockConfiguration={
                "BlockPublicAcls": True, "IgnorePublicAcls": True, "BlockPublicPolicy": True,
                "RestrictPublicBuckets": True})
        except ClientError:
            pass  # MinIO has no public-access-block API; its buckets are private unless a policy is set


_stores: dict[tuple, object] = {}
_lock = threading.Lock()


def store_for(backend: str, cfg: Settings):
    """Store instance for a backend name recorded on a document version (cached)."""
    if backend == "local":
        key = ("local", str(Path(cfg.storage_dir).resolve()))
    elif backend == "s3":
        key = ("s3", cfg.s3_endpoint_url, cfg.s3_bucket, cfg.s3_region, cfg.s3_access_key_id,
               cfg.s3_public_endpoint_url, cfg.s3_force_path_style)
    else:
        raise StorageError(f"unknown storage backend {backend!r}")
    with _lock:
        if key not in _stores:
            _stores[key] = LocalObjectStore(cfg.storage_dir) if backend == "local" else S3ObjectStore(cfg)
        return _stores[key]


def default_store(cfg: Settings):
    return store_for(cfg.storage_backend, cfg)
